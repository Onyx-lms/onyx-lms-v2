/**
 * Bakes the supplied certificate artwork into a TypeScript module.
 *
 *   node tools/onyx/build-certificate-template.mjs
 *
 * WHY A GENERATED MODULE, and not a file read at runtime. Nothing on a request
 * path in this app reads from disk, and the one binary asset that already
 * exists -- the Onyx mark in pdf-mark.ts -- is a generated module for the same
 * reason: Next traces what it can see in the import graph, and an asset loaded
 * by a path it computes at runtime is exactly what file tracing misses. A
 * certificate that renders locally and 500s on the deployment is the failure
 * this avoids.
 *
 * WHY ONE TEMPLATE AND NOT FOUR. The four supplied PDFs (course completion,
 * internship, performance, project completion) are byte-identical in their
 * artwork -- verified by hashing every embedded image in each: all four share
 * the same eleven. The only difference is the title line, which sits on plain
 * white and is therefore cheaper to draw than to store three more times.
 * Shipping one template keeps ~1.4 MB of duplicated base64 out of the bundle
 * and makes a fifth certificate type a line of copy rather than a new asset.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = new URL('../../', import.meta.url).pathname.replace(/^[/]([A-Za-z]:)/, '$1');
const SOURCE = path.join(ROOT, 'design/certificates/course-completion.pdf');
const OUT = path.join(ROOT, 'packages/core/src/format/certificate-template.ts');

const pdf = fs.readFileSync(SOURCE);
const b64 = pdf.toString('base64');

// 76 characters a line: long enough not to bloat the file with quotes, short
// enough that an editor and a diff can both cope with it.
const lines = [];
for (let i = 0; i < b64.length; i += 76) lines.push("  '" + b64.slice(i, i + 76) + "',");

const file = `/**
 * The certificate artwork, as supplied, base64 of a single-page A4 landscape
 * PDF. GENERATED by tools/onyx/build-certificate-template.mjs -- edit the
 * source in design/certificates/ and re-run it rather than editing this file.
 *
 * Everything a reader recognises is in here already: the accreditation marks,
 * the gold border, ONYXEDUTECH, "THIS CERTIFICATE IS PRESENTED TO", the rule
 * the holder's name sits on, #startupindia and the VERIFIED badge. What is NOT
 * in here is anything that changes per credential -- see certificate-doc.ts,
 * which draws those over the top.
 *
 * Source: ${path.basename(SOURCE)} (${pdf.length.toLocaleString('en-GB')} bytes)
 */
export const CERTIFICATE_TEMPLATE_B64 = [
${lines.join('\n')}
].join('');
`;

fs.writeFileSync(OUT, file);
console.log('wrote', path.relative(ROOT, OUT),
  '--', pdf.length.toLocaleString('en-GB'), 'bytes ->', b64.length.toLocaleString('en-GB'), 'base64');
